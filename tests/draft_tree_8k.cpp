// The 8K release-lattice selector gate: runs the selectors on the recorded 8K lattice fixture (our served text, j1540) and
// prices accepted tokens per verify pass. A node lands iff its root-to-node path is a prefix of the recorded greedy
// continuation - exactly what the target's greedy verify checks - so the number is the row's acceptance at <= 15 nodes.
//
// ctest runs the baseline assertions only (the chain and this build's default policy against recorded values). The release
// gate is `test-draft-tree-8k --gate`: it fails until the default policy reaches the bar that beats TensorFold at 8K
// (>= 4.90 accepted per pass, TensorFold's measured 4.88 at a 79.6 ms step; the candidate sets support 5.83).
//
// Fixture: tests/data/lattice8k.bin (generated by ai_workspace mac/make_lattice_fixture.py from the j1540 dump). Override
// the path and the gate bar with TQLLM_TEST_LATTICE_8K / TQLLM_GATE_8K.
#include <cmath>
#include <cstdio>
#include <cstdlib>
#include <cstring>
#include <fstream>
#include <map>
#include <stdexcept>
#include <string>
#include <vector>

#include "draft_tree.hpp"

namespace {
constexpr int kTopK = 16, kRank = 256;
// measured on the 12-step fixture (tests/data/lattice8k.bin, generated from the j1540 8K dump): chain 3.167, default
// policy 4.250. The full 86-step dump reads chain 2.97 / policy 4.05, so the sample is a fair, if slightly easier, stand-in.
constexpr double kChainBaseline = 3.167;
constexpr double kDefaultPolicyBaseline = 4.250;
constexpr double kGateAccepted = 4.90;   // beats TensorFold's 4.88 at 8K (79.6 ms step); the candidate sets support 5.83

struct Step {
    int produced = 0;
    uint32_t anchor = 0;
    int count = 0;
    std::vector<uint32_t> truth;
    int rows = 0;
    std::vector<uint32_t> tokens;   // [rows * topk]
    std::vector<float> unary;       // [rows * topk]
    std::vector<float> gate;        // [rows * rank]
    std::vector<float> successor;   // [rows * topk * rank]
    std::vector<uint32_t> codebook_tokens;
    std::vector<float> predecessor; // [codebook_tokens * rank]
};

template <class T>
std::vector<T> read_array(std::ifstream& in, size_t count) {
    std::vector<T> out(count);
    in.read(reinterpret_cast<char*>(out.data()), std::streamsize(sizeof(T) * count));
    if (!in) throw std::runtime_error("fixture truncated");
    return out;
}
std::vector<Step> load(const std::string& path) {
    std::ifstream in(path, std::ios::binary);
    if (!in) throw std::runtime_error("cannot open fixture " + path);
    char magic[4];
    int version = 0, steps = 0, topk = 0, rank = 0;
    in.read(magic, 4);
    in.read(reinterpret_cast<char*>(&version), sizeof(int));
    in.read(reinterpret_cast<char*>(&steps), sizeof(int));
    in.read(reinterpret_cast<char*>(&topk), sizeof(int));
    in.read(reinterpret_cast<char*>(&rank), sizeof(int));
    if (std::memcmp(magic, "DFLT", 4) || version != 1 || topk != kTopK || rank != kRank)
        throw std::runtime_error("bad fixture header");
    std::vector<Step> out;
    for (int s = 0; s < steps; ++s) {
        Step step;
        in.read(reinterpret_cast<char*>(&step.produced), sizeof(int));
        in.read(reinterpret_cast<char*>(&step.anchor), sizeof(uint32_t));
        in.read(reinterpret_cast<char*>(&step.count), sizeof(int));
        in.read(reinterpret_cast<char*>(&step.rows), sizeof(int));
        if (!in || step.count < 1 || step.count > 15 || step.rows < step.count + 1 || step.rows > 16)
            throw std::runtime_error("bad fixture step");
        step.truth = read_array<uint32_t>(in, size_t(step.count));
        // the fixture carries every block row (row 0 is the anchor); the selector uses rows 1..count
        step.tokens = read_array<uint32_t>(in, size_t(step.rows) * kTopK);
        step.unary = read_array<float>(in, size_t(step.rows) * kTopK);
        step.gate = read_array<float>(in, size_t(step.rows) * kRank);
        step.successor = read_array<float>(in, size_t(step.rows) * kTopK * kRank);
        int codebook = 0;
        in.read(reinterpret_cast<char*>(&codebook), sizeof(int));
        if (!in || codebook < 1) throw std::runtime_error("bad fixture codebook");
        step.codebook_tokens = read_array<uint32_t>(in, size_t(codebook));
        step.predecessor = read_array<float>(in, size_t(codebook) * kRank);
        out.push_back(std::move(step));
    }
    return out;
}

// the recorded block row r of a step (r = 0 is the anchor row, rows 1..count are the drafted positions)
struct StepView {
    const Step& step;
    std::map<uint32_t, const float*> rows;
    StepView(const Step& s) : step(s) {
        for (size_t i = 0; i < step.codebook_tokens.size(); ++i)
            rows[step.codebook_tokens[i]] = step.predecessor.data() + i * kRank;
    }
    const float* predecessor_row(uint32_t token) const {
        auto it = rows.find(token);
        return it == rows.end() ? nullptr : it->second;
    }
    tqllm::DraftLattice lattice() {
        tqllm::DraftLattice l;
        l.positions = step.count;
        l.topk = kTopK;
        l.rank = kRank;
        l.tokens = step.tokens.data() + kTopK;              // skip the anchor row
        l.unary = step.unary.data() + kTopK;
        l.gate = step.gate.data() + kRank;                  // skip the anchor row
        l.successor = step.successor.data() + size_t(kTopK) * kRank;
        l.predecessor = &callback;
        l.context = this;
        return l;
    }
    static const float* callback(void* context, uint32_t token) {
        return static_cast<StepView*>(context)->predecessor_row(token);
    }
};

// deepest tree path that is a prefix of the recorded continuation, plus the bonus token
int accepted(const tqllm::DraftTree& tree, const std::vector<uint32_t>& truth) {
    std::vector<int> depth(tree.tokens.size(), 0);
    for (size_t row = 0; row < tree.tokens.size(); ++row)
        depth[row] = tree.parents[row] < 0 ? 0 : depth[size_t(tree.parents[row])] + 1;
    int best = 0;
    for (size_t row = 0; row < tree.tokens.size(); ++row) {
        std::vector<uint32_t> path;
        for (int node = int(row); node >= 0; node = tree.parents[size_t(node)]) path.push_back(tree.tokens[size_t(node)]);
        if (int(path.size()) <= int(truth.size()) &&
            std::equal(path.rbegin(), path.rend(), truth.begin())) {
            best = std::max(best, int(path.size()));
        }
    }
    return best + 1;
}
}  // namespace

int main(int argc, char** argv) {
    try {
        const char* path = std::getenv("TQLLM_TEST_LATTICE_8K");
        const std::string fixture = path ? path : "tests/data/lattice8k.bin";
        const bool gate = argc > 1 && std::string(argv[1]) == "--gate";
        const auto steps = load(fixture);
        const tqllm::DraftTreeOptions defaults;  // this build's policy (the plugin's default)
        tqllm::DraftTreeOptions chain = defaults;
        chain.children = 1;
        chain.nodes = 15;
        chain.edge = 1.0f;
        chain.tau = 1.0f;
        double chain_sum = 0, policy_sum = 0;
        for (const auto& step : steps) {
            StepView view(step);
            const int chain_accepted = accepted(tqllm::best_first_tree(view.lattice(), step.anchor, chain), step.truth);
            const int policy_accepted = accepted(tqllm::best_first_tree(view.lattice(), step.anchor, defaults), step.truth);
            chain_sum += chain_accepted;
            policy_sum += policy_accepted;
            std::printf("step %2d: chain %2d  policy %2d\n", step.produced, chain_accepted, policy_accepted);
        }
        const double n = double(steps.size());
        std::printf("8K fixture: %d steps, chain %.3f, policy %.3f accepted per verify pass (gate %.2f)\n", int(steps.size()),
                    chain_sum / n, policy_sum / n, kGateAccepted);
        if (gate) {
            if (policy_sum / n < kGateAccepted) {
                std::printf("FAIL gate: policy %.3f < %.2f accepted per pass\n", policy_sum / n, kGateAccepted);
                return 1;
            }
            std::printf("PASS gate: policy %.3f >= %.2f accepted per pass\n", policy_sum / n, kGateAccepted);
            return 0;
        }
        // baseline sanity (ctest): the fixture and loader are right when the chain and the default policy land in band
        if (std::fabs(chain_sum / n - kChainBaseline) > 0.15) {
            std::printf("FAIL baseline: chain %.3f, recorded %.3f\n", chain_sum / n, kChainBaseline);
            return 1;
        }
        if (std::fabs(policy_sum / n - kDefaultPolicyBaseline) > 0.15) {
            std::printf("FAIL baseline: policy %.3f, recorded %.3f\n", policy_sum / n, kDefaultPolicyBaseline);
            return 1;
        }
        std::printf("draft_tree_8k: ok\n");
        return 0;
    } catch (const std::exception& error) {
        std::printf("draft_tree_8k: %s\n", error.what());
        return 1;
    }
}